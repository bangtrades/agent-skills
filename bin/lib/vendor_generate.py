#!/usr/bin/env python3
"""Generate namespaced registry skills from a vendored upstream tree.

Invoked by bin/sync-upstream.sh. Reads env: VDIR, SKILLS, PREFIX, NAME,
REPO, TAG, NEW_SHA, NEW_DATE.

Contract
--------
* Upstream content under vendor/<name>/src is PRISTINE and never modified.
* Generated copies under skills/<prefix><name>/ are DERIVED and disposable —
  the whole set is deleted and rebuilt on every sync, so local edits are lost
  by design. Fork a skill into the authored lane if you want to change it.
* Exactly three transforms are applied, all deterministic:
    1. frontmatter `name:`            -> prefixed (registry lint requires
                                         name == directory name)
    2. sibling `/skill` references    -> prefixed, so the chain still resolves
    3. openai.yaml `display_name`     -> tagged, so the Codex picker can tell
                                         a vendored skill from ours
  Everything else is copied byte-for-byte, including
  `disable-model-invocation` and `policy.allow_implicit_invocation`.
"""

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

VDIR = Path(os.environ["VDIR"])
SKILLS = Path(os.environ["SKILLS"])
PREFIX = os.environ["PREFIX"]
NAME = os.environ["NAME"]
REPO = os.environ["REPO"]
TAG = os.environ["TAG"]
SHA = os.environ["NEW_SHA"]
CDATE = os.environ["NEW_DATE"]

SRC = VDIR / "src"
FM = re.compile(r"\A---\n(.*?\n)---\n", re.S)


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def fm_get(text: str, key: str):
    m = FM.match(text)
    if not m:
        return None
    for line in m.group(1).splitlines():
        if line.startswith(key + ":"):
            return line[len(key) + 1:].strip()
    return None


# ---- discover upstream skills ----------------------------------------------
skills = []           # (upstream_name, bucket, dir)
for skill_md in sorted(SRC.rglob("SKILL.md")):
    d = skill_md.parent
    rel = d.relative_to(SRC)
    bucket = rel.parts[0] if len(rel.parts) > 1 else "(root)"
    upstream_name = fm_get(skill_md.read_text(encoding="utf-8"), "name") or d.name
    skills.append((upstream_name, bucket, d))

if not skills:
    sys.exit("FATAL: no SKILL.md found under %s" % SRC)

names = sorted({n for n, _, _ in skills})

# which skills the upstream plugin promotes (vs beta / misc buckets)
promoted = set()
pj = VDIR / ".claude-plugin" / "plugin.json"
if pj.exists():
    promoted = {Path(s).name for s in json.loads(pj.read_text())["skills"]}

# ---- reference rewriting ----------------------------------------------------
# Match `/skill-name` only when it is a slash-command reference, never a path
# segment. The char before the slash must not be a word char, '-', '.' or '/',
# which excludes URLs like .../skills/engineering/tdd/SKILL.md.
REF = re.compile(
    r"(?<![\w\-./])/(" + "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True)) + r")\b"
)


def rewrite_body(text: str) -> tuple:
    n = [0]

    def sub(m):
        n[0] += 1
        return "/" + PREFIX + m.group(1)

    return REF.sub(sub, text), n[0]


def rewrite_skill_md(text: str, upstream_name: str) -> tuple:
    m = FM.match(text)
    if not m:
        raise SystemExit("FATAL: %s has no frontmatter" % upstream_name)
    fm_block, body = m.group(1), text[m.end():]

    out = []
    for line in fm_block.splitlines():
        if line.startswith("name:"):
            out.append("name: " + PREFIX + upstream_name)
        else:
            out.append(line)
    fm_new = "\n".join(out) + "\n"

    body_new, refs = rewrite_body(body)
    provenance = (
        "<!-- VENDORED from %s @ %s (%s). Generated by bin/sync-upstream.sh — "
        "do not edit; changes are overwritten on the next sync. "
        "Upstream name: %s -->\n\n" % (REPO, TAG, CDATE, upstream_name)
    )
    return "---\n" + fm_new + "---\n\n" + provenance + body_new.lstrip("\n"), refs


DISPLAY = re.compile(r"^(\s*display_name:\s*)([\"']?)(.*?)\2\s*$", re.M)


def rewrite_openai_yaml(text: str) -> str:
    return DISPLAY.sub(lambda m: '%s"[MP] %s"' % (m.group(1), m.group(3)), text, count=1)


# ---- generate ---------------------------------------------------------------
manifest = []
total_refs = 0

for upstream_name, bucket, d in skills:
    target_name = PREFIX + upstream_name
    dst = SKILLS / target_name
    if dst.exists():
        # Some mounts refuse unlink via rmtree's fd walk; fall back to /bin/rm.
        shutil.rmtree(dst, ignore_errors=True)
        if dst.exists():
            subprocess.run(["rm", "-rf", str(dst)], check=True)
    shutil.copytree(d, dst, ignore=shutil.ignore_patterns(".DS_Store"))

    md = dst / "SKILL.md"
    text = md.read_text(encoding="utf-8")
    new_text, refs = rewrite_skill_md(text, upstream_name)
    md.write_text(new_text, encoding="utf-8")
    total_refs += refs

    oy = dst / "agents" / "openai.yaml"
    if oy.exists():
        oy.write_text(rewrite_openai_yaml(oy.read_text(encoding="utf-8")), encoding="utf-8")

    # rewrite references in every other text file the skill carries
    # (.md briefs, .sh templates, config stubs — upstream ships all three)
    for extra in sorted(dst.rglob("*")):
        if not extra.is_file() or extra == md or extra.name == "openai.yaml":
            continue
        try:
            t = extra.read_text(encoding="utf-8")
        except (UnicodeDecodeError, ValueError):
            continue  # binary asset — copy through untouched
        t2, r = rewrite_body(t)
        if r:
            extra.write_text(t2, encoding="utf-8")
            total_refs += r

    fm_src = d.joinpath("SKILL.md").read_text(encoding="utf-8")
    user_invoked = (fm_get(fm_src, "disable-model-invocation") or "").lower() == "true"

    manifest.append({
        "name": target_name,
        "upstream_name": upstream_name,
        "bucket": bucket,
        "promoted": d.name in promoted,
        "invocation": "user" if user_invoked else "model",
        "has_codex_sidecar": (dst / "agents" / "openai.yaml").exists(),
        "upstream_path": str(d.relative_to(VDIR)),
        "files": sorted(str(p.relative_to(dst)) for p in dst.rglob("*") if p.is_file()),
        "skill_md_sha256": sha256(md),
    })

manifest.sort(key=lambda r: r["name"])
(VDIR / "MANIFEST.json").write_text(
    json.dumps(
        {
            "vendor": NAME,
            "repo": REPO,
            "tag": TAG,
            "commit": SHA,
            "commit_date": CDATE,
            "prefix": PREFIX,
            "skill_count": len(manifest),
            "user_invoked": sum(1 for r in manifest if r["invocation"] == "user"),
            "model_invoked": sum(1 for r in manifest if r["invocation"] == "model"),
            "promoted": sum(1 for r in manifest if r["promoted"]),
            "skills": manifest,
        },
        indent=2,
    )
    + "\n",
    encoding="utf-8",
)

print("    generated : %d skills (%d user-invoked, %d model-invoked)"
      % (len(manifest),
         sum(1 for r in manifest if r["invocation"] == "user"),
         sum(1 for r in manifest if r["invocation"] == "model")))
print("    sidecars  : %d/%d carry agents/openai.yaml"
      % (sum(1 for r in manifest if r["has_codex_sidecar"]), len(manifest)))
print("    refs      : %d cross-references rewritten" % total_refs)
print("    manifest  : %s" % (VDIR / "MANIFEST.json").relative_to(VDIR.parent.parent))
